import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import { ruleIdToIdentifier, rulePackLayouts } from "./layout.mjs";

const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../..",
);
const checkOnly = process.argv.includes("--check");
const changed = [];

const normalize = (value) => value.replaceAll("\r\n", "\n");
const writeGenerated = (filePath, content) => {
  const next = normalize(content);
  const current = fs.existsSync(filePath)
    ? normalize(fs.readFileSync(filePath, "utf8"))
    : null;
  if (current === next) return;

  changed.push(path.relative(root, filePath));
  if (!checkOnly) {
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, next);
  }
};

const getRuleFiles = (layout) => {
  const directory = path.join(
    root,
    "packages/rules/src/rules",
    layout.directory,
  );
  if (!fs.existsSync(directory)) return [];

  return fs
    .readdirSync(directory)
    .filter((name) =>
      new RegExp(`^${layout.prefix}-\\d{3}-[a-z0-9-]+\\.ts$`).test(name),
    )
    .sort((left, right) =>
      left.localeCompare(right, undefined, { numeric: true }),
    );
};

for (const layout of rulePackLayouts) {
  const files = getRuleFiles(layout);
  if (!files.length) {
    throw new Error(`No rules found for pack ${layout.pack}.`);
  }

  const imports = files.map((file) => {
    const ruleId = file.match(/^([A-Z0-9]+-\d{3})-/)?.[1];
    if (!ruleId) {
      throw new Error(`Invalid rule filename: ${file}`);
    }

    const identifier = `${ruleIdToIdentifier(ruleId)}Rule`;
    const source = fs.readFileSync(
      path.join(root, "packages/rules/src/rules", layout.directory, file),
      "utf8",
    );
    if (!new RegExp(`export const ${identifier}\\b`).test(source)) {
      throw new Error(`${file} must export \`${identifier}\`.`);
    }

    return { file, identifier };
  });

  const content = [
    'import type { CodingRule } from "../../types";',
    ...imports.map(
      ({ file, identifier }) => `import { ${identifier} } from "./${file}";`,
    ),
    "",
    `export const ${layout.exportName} = [`,
    ...imports.map(({ identifier }) => `  ${identifier},`),
    "] satisfies readonly CodingRule[];",
    "",
  ].join("\n");
  writeGenerated(
    path.join(root, "packages/rules/src/rules", layout.directory, "index.ts"),
    content,
  );
}

const rulesRootIndex = [
  "// Generated by scripts/rules/generate-registries.mjs. Do not edit by hand.",
  ...rulePackLayouts.map(
    ({ directory, exportName }) =>
      `export { ${exportName} } from "./${directory}/index.ts";`,
  ),
  "",
].join("\n");
writeGenerated(
  path.join(root, "packages/rules/src/rules/index.ts"),
  rulesRootIndex,
);

const detectorImports = [];
const detectorSpreads = [];
for (const layout of rulePackLayouts.filter(({ analyzer }) => analyzer)) {
  const directory = path.join(
    root,
    "packages/analyzer/src/detectors",
    layout.directory,
  );
  if (!fs.existsSync(directory)) continue;

  const files = fs
    .readdirSync(directory)
    .filter((name) =>
      new RegExp(`^${layout.prefix}-\\d{3}-[a-z0-9-]+\\.ts$`).test(name),
    )
    .sort((left, right) =>
      left.localeCompare(right, undefined, { numeric: true }),
    );

  for (const file of files) {
    const ruleId = file.match(/^([A-Z0-9]+-\d{3})-/)?.[1];
    if (!ruleId) {
      throw new Error(`Invalid detector filename: ${file}`);
    }

    const identifier = `${ruleIdToIdentifier(ruleId)}Detectors`;
    const source = fs.readFileSync(path.join(directory, file), "utf8");
    if (!new RegExp(`export const ${identifier}\\b`).test(source)) {
      throw new Error(`${file} must export \`${identifier}\`.`);
    }

    detectorImports.push(
      `import { ${identifier} } from "./${layout.directory}/${file}";`,
    );
    detectorSpreads.push(`  ...${identifier},`);
  }
}

const detectorRegistry = [
  "// Generated by scripts/rules/generate-registries.mjs. Do not edit by hand.",
  'import type { Detector } from "../types.ts";',
  ...detectorImports,
  "",
  "export const detectors = [",
  ...detectorSpreads,
  "] satisfies readonly Detector[];",
  "",
].join("\n");
writeGenerated(
  path.join(root, "packages/analyzer/src/detectors/registry.generated.ts"),
  detectorRegistry,
);

if (checkOnly && changed.length) {
  console.error(
    `Generated registries are stale:\n${changed
      .map((file) => `- ${file}`)
      .join("\n")}`,
  );
  process.exitCode = 1;
} else if (changed.length) {
  console.log(
    `Updated ${changed.length} generated registr${changed.length === 1 ? "y" : "ies"}.`,
  );
} else {
  console.log("Rule and detector registries are current.");
}
